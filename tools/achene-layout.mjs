// Copies achene's panel layout into js/achene-layout.js for the achene view.
//
// achene's hardware/layout.json is generated from its KiCad PCB
// (hardware/tools/make_layout.py): every encoder, key, LED, jack and the OLED,
// in panel millimetres. diii keeps a copy, so the two repos share nothing at
// build time; run this after the PCB moves something.
//
//   node tools/achene-layout.mjs [path/to/layout.json]   (default ../achene/hardware/layout.json)

import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const source = process.argv[2] || join(root, '..', 'achene', 'hardware', 'layout.json');
const out = join(root, 'js', 'achene-layout.js');

const layout = JSON.parse(await readFile(source, 'utf8'));
const pick = (o, keys) => Object.fromEntries(keys.filter((k) => k in o).map((k) => [k, o[k]]));

// only what the view draws
const data = {
    panel: pick(layout.panel, ['w', 'h', 'hp']),
    sizes: layout.sizes,
    encoders: layout.encoders.map((e) => pick(e, ['n', 'x', 'y'])),
    keys: layout.keys.map((k) => pick(k, ['n', 'x', 'y', 'led'])),
    oled: pick(layout.oled, ['glass', 'active', 'pixels']),
    jacks: layout.jacks.map((j) => pick(j, ['label', 'x', 'y']))
};

const text = `// @ts-check
// Generated by tools/achene-layout.mjs from achene's hardware/layout.json
// (itself generated from the KiCad PCB); run that again rather than editing.
// Millimetres, panel coordinates: origin top-left, x right, y down.

export const ACHENE_LAYOUT = ${JSON.stringify(data, null, 4)};
`;
await writeFile(out, text);
console.log(
    `js/achene-layout.js: ${data.encoders.length} encoders, ${data.keys.length} keys, ${data.jacks.length} jacks (from ${source})`
);
